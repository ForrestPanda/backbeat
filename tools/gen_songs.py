"""fm1-drummer: the factory songs, packed (tools/fm1_song.py) into a C header for firmware/src/sng.c.

A song slot that was never written plays its factory song (the device fresh from the installer, the fm1-emu
emulator); one written by fm1_song.py --put or the editor plays that, one erased stays empty.

  tools/gen_songs.py OUT.h [SONG.json ...]     (default: every songs/*.json, by file name, slots 0..)"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fm1_song  # noqa: E402

SRC = Path(__file__).resolve().parents[1]
SLOTS = 8                                    # seq.c SNG_SLOTS


def main(out, files):
    if not files:                            # the songs in songs/, by file name (the first 8)
        files = sorted((SRC / "songs").glob("*.json"))
        for f in files[SLOTS:]:
            print(f"songs: {f.name} left out (8 slots)")
        files = files[:SLOTS]
    if len(files) > SLOTS:
        sys.exit(f"gen_songs: at most {SLOTS} factory songs")
    L = ["/* generated by tools/gen_songs.py: the factory songs, packed (SNG2) */"]
    names = []
    for k, f in enumerate(files):
        blob = fm1_song.pack(json.loads(Path(f).read_text()))
        L.append(f"static const uint8_t SNG_FACTORY_{k}[{len(blob)}] = {{")
        L += ["    " + ", ".join(str(b) for b in blob[i:i + 24]) + "," for i in range(0, len(blob), 24)]
        L.append("};")
        names.append((k, len(blob), blob[4:16].rstrip(b"\0").decode("ascii", "replace")))
    L.append("static const struct { const uint8_t *b; uint16_t n; } SNG_FACTORY[] = {")
    L += [f"    {{SNG_FACTORY_{k}, {n}}},   /* {nm} */" for k, n, nm in names]
    if not names:
        L.append("    {0, 0},")
    L.append("};")
    L.append(f"#define SNG_NFACTORY {len(names)}u")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"songs: {len(names)} factory songs, {sum(n for _, n, _ in names)} B: " + ", ".join(nm for _, _, nm in names))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
